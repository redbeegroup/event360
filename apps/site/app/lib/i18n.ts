export type Lang = 'en' | 'my';
export const LANGS: Lang[] = ['en', 'my'];
export const isLang = (s: string): s is Lang => s === 'en' || s === 'my';

/** English lives at the root, Myanmar under /my. */
export const href = (lang: Lang, path: string) => (lang === 'en' ? path : `/my${path === '/' ? '' : path}`);

export const pick = (lang: Lang, en: string | null | undefined, my: string | null | undefined) => (lang === 'my' && my ? my : en ?? '');

const TZ = 'Asia/Yangon';
const loc = (lang: Lang) => (lang === 'my' ? 'my-MM' : 'en-GB');

export const fmtDay = (d: string | Date, lang: Lang) => new Intl.DateTimeFormat(loc(lang), { timeZone: TZ, weekday: 'short', day: 'numeric', month: 'short' }).format(new Date(d));
export const fmtDayLong = (d: string | Date, lang: Lang) =>
  new Intl.DateTimeFormat(loc(lang), { timeZone: TZ, weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }).format(new Date(d));
export const fmtTime = (d: string | Date, lang: Lang) => new Intl.DateTimeFormat(lang === 'my' ? 'my-MM' : 'en-US', { timeZone: TZ, hour: 'numeric', minute: '2-digit' }).format(new Date(d));
export const dayParts = (d: string | Date) => {
  const p = new Intl.DateTimeFormat('en-GB', { timeZone: TZ, day: 'numeric', month: 'short' }).formatToParts(new Date(d));
  return { day: p.find((x) => x.type === 'day')!.value, month: p.find((x) => x.type === 'month')!.value };
};
/** Basis points as a percentage string: 1000 → "10", 750 → "7.5". */
export const fmtPct = (bp: number) => String(bp / 100);
export const fmtMmk = (n: number, lang: Lang) => `${new Intl.NumberFormat(lang === 'my' ? 'my-MM' : 'en-US').format(n)} ${lang === 'my' ? 'ကျပ်' : 'MMK'}`;

